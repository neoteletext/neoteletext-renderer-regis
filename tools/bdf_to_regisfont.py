"""Turn a 10x20 BDF terminal font into the renderer's font text.

The output holds two strikes of every printable character:

  [strike 20]  8x20, used when the text cell height is a multiple of 20.
               A VT340 screenshot shows size-1 ReGIS text drawn from twenty
               distinct rows, not from a ten-row shape doubled.
  [strike 10]  8x10, the stored cell of the manual (chapter 7, "Character
               Format"), used for every other size.

The source cell is 10 pixels wide and a ReGIS cell 8. Columns 1 to 8 are
kept: with that alignment the digit 0 matches a VT340 screenshot exactly.
Glyphs that use nine columns have their two most alike neighbouring columns
merged, so no stroke is lost. The ten-row strike merges the pairs of rows
that differ least over the whole font, one mapping for every glyph so they
share a baseline.

Usage: python3 -I bdf_to_regisfont.py font.bdf > font.regisfont
"""

import sys

SOURCE_WIDTH = 10
SOURCE_HEIGHT = 20
FIRST_KEPT_COLUMN = 1
CELL_WIDTH = 8
TALL_ROWS = 20
SHORT_ROWS = 10
# Printable codes: ASCII 0x20-0x7E and the Latin-1 right half 0xA0-0xFF.
PRINTABLE = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
NO_BREAK_SPACE, SPACE = 0xA0, 0x20
MAX_BDF_BYTES = 4 * 1024 * 1024

assert SOURCE_HEIGHT == TALL_ROWS
assert FIRST_KEPT_COLUMN + CELL_WIDTH <= SOURCE_WIDTH


def read_glyphs(path):
    with open(path, "rb") as source:
        data = source.read(MAX_BDF_BYTES + 1)
    if len(data) > MAX_BDF_BYTES:
        raise SystemExit(f"{path}: larger than {MAX_BDF_BYTES} bytes")
    glyphs, encoding, rows, box = {}, None, None, None
    for line in data.decode("latin-1").splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == "ENCODING":
            encoding = int(fields[1])
        elif fields[0] == "BBX":
            box = tuple(int(value) for value in fields[1:5])
        elif fields[0] == "BITMAP":
            if box != (SOURCE_WIDTH, SOURCE_HEIGHT, 0, -5):
                raise SystemExit(f"glyph {encoding}: unexpected BBX {box}")
            rows = []
        elif fields[0] == "ENDCHAR":
            if rows is None or len(rows) != SOURCE_HEIGHT:
                raise SystemExit(f"glyph {encoding}: expected {SOURCE_HEIGHT} rows")
            glyphs[encoding] = rows
            rows = None
        elif rows is not None:
            # BDF rows are padded to whole bytes, leftmost pixel in the top bit.
            rows.append(int(fields[0], 16) >> (len(fields[0]) * 4 - SOURCE_WIDTH))
    return glyphs


def narrow(rows):
    """The glyph as rows of CELL_WIDTH pixels, leftmost in the top bit."""
    columns = [[(row >> (SOURCE_WIDTH - 1 - x)) & 1 for row in rows] for x in range(SOURCE_WIDTH)]
    kept = list(range(FIRST_KEPT_COLUMN, FIRST_KEPT_COLUMN + CELL_WIDTH))
    inked = [x for x in range(SOURCE_WIDTH) if any(columns[x])]
    if inked and (inked[0] < kept[0] or inked[-1] > kept[-1]):
        if inked[-1] - inked[0] > CELL_WIDTH:
            raise SystemExit("glyph wider than nine columns")
        start = min(inked[0], SOURCE_WIDTH - (CELL_WIDTH + 1))
        span = list(range(start, start + CELL_WIDTH + 1))
        difference = lambda i: sum(a != b for a, b in zip(columns[span[i]], columns[span[i + 1]]))
        merge = min(range(len(span) - 1), key=difference)
        merged = [a | b for a, b in zip(columns[span[merge]], columns[span[merge + 1]])]
        chosen = [columns[x] for x in span[:merge]] + [merged] + [columns[x] for x in span[merge + 2:]]
    else:
        chosen = [columns[x] for x in kept]
    return [sum(chosen[x][y] << (CELL_WIDTH - 1 - x) for x in range(CELL_WIDTH)) for y in range(len(rows))]


def merged_row(rows, group):
    value = 0
    for y in group:
        value |= rows[y]
    return value


def row_groups(glyphs, height):
    """Which source rows make each of `height` rows, the same for every glyph."""
    groups = [[y] for y in range(TALL_ROWS)]
    while len(groups) > height:
        cost = lambda i: sum(
            bin(merged_row(rows, groups[i]) ^ merged_row(rows, groups[i + 1])).count("1") for rows in glyphs.values()
        )
        i = min(range(len(groups) - 1), key=cost)
        groups[i:i + 2] = [groups[i] + groups[i + 1]]
    return groups


def main():
    source = read_glyphs(sys.argv[1])
    source.setdefault(NO_BREAK_SPACE, source[SPACE])
    glyphs = {code: narrow(source[code]) for code in PRINTABLE if code in source}
    groups = row_groups(glyphs, SHORT_ROWS)
    print("# DEC VWSVT0 terminal font, narrowed to the 8-pixel ReGIS cell.")
    print("# Generated by tools/bdf_to_regisfont.py; do not edit.")
    print(f"\n[strike {TALL_ROWS}]")
    for code, rows in glyphs.items():
        print(f"{code:02X} " + " ".join(f"{row:02X}" for row in rows))
    print(f"\n# Source rows merged into each row: {groups}")
    print(f"[strike {SHORT_ROWS}]")
    for code, rows in glyphs.items():
        print(f"{code:02X} " + " ".join(f"{merged_row(rows, group):02X}" for group in groups))


if __name__ == "__main__":
    main()
