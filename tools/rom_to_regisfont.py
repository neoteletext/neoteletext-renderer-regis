"""Turn the VT340's character generator ROM into the renderer's font text.

The ROM (23-236E6, at position E49 on the logic board, 32 KiB) is a bitmap
256 pixels wide: sixteen character cells side by side, each a 16-bit word
a scan line, low byte first, twenty scan lines a cell. The terminal's
graphics processor copies ReGIS characters out of it as 8x20 rectangles
and scales them to the size asked for.

  0x20-0x7E  The ROM has shapes drawn eight pixels wide for ReGIS, apart
             from its text shapes. They begin at scan line 501, bit 0 the
             leftmost pixel. Rendered with them, the labels of the grid
             test match a VT340 screen capture pixel for pixel.
  0xA0-0xFF  ReGIS has no shapes of its own for these: the terminal draws
             the 10-pixel text shape, less its first and last columns.
             The text cell for a code starts at scan line 20 * (code / 16).
  ten rows   The ROM follows the tall ReGIS shapes with ten-row ones. For
             0xA0-0xFF each pair of rows is merged.

Usage: python3 -I rom_to_regisfont.py vt340e49.bin > vt340.regisfont
"""

import hashlib
import sys

ROM_BYTES = 32768
ROM_SHA256 = "eb0426b403e8bcd4dc72b448f6253cad22cb30386b22d89b0b57667a901f135e"
CELLS_ACROSS = 16
BYTES_PER_CELL = 2
BYTES_PER_LINE = CELLS_ACROSS * BYTES_PER_CELL
TALL_ROWS = 20
SHORT_ROWS = 10
CELL_WIDTH = 8
# Scan line of the first ReGIS shape (space), found by matching a glyph
# captured from a VT340 screen and confirmed by the grid test.
REGIS_FIRST_LINE = 501
REGIS_FIRST_CODE = 0x20
REGIS_CODES_IN_TABLE = 0x80 - REGIS_FIRST_CODE
REGIS_SHORT_FIRST_LINE = REGIS_FIRST_LINE + REGIS_CODES_IN_TABLE // CELLS_ACROSS * TALL_ROWS
# A text shape is ten pixels in bits 0-9; ReGIS takes bits 1-8.
TEXT_FIRST_KEPT_BIT = 1
ASCII = range(0x20, 0x7F)
LATIN_RIGHT_HALF = range(0xA0, 0x100)
NO_BREAK_SPACE = 0xA0

assert (REGIS_SHORT_FIRST_LINE + (REGIS_CODES_IN_TABLE // CELLS_ACROSS - 1) * TALL_ROWS + SHORT_ROWS) * BYTES_PER_LINE <= ROM_BYTES
assert TALL_ROWS == 2 * SHORT_ROWS


def word(rom, line, column):
    at = line * BYTES_PER_LINE + column * BYTES_PER_CELL
    return rom[at] | rom[at + 1] << 8


def packed(bits):
    """Eight pixels, bit 0 leftmost, as the font text has them: leftmost in the top bit."""
    return sum(((bits >> bit) & 1) << (CELL_WIDTH - 1 - bit) for bit in range(CELL_WIDTH))


def regis_rows(rom, first_line, code, count):
    index = code - REGIS_FIRST_CODE
    line = first_line + index // CELLS_ACROSS * TALL_ROWS
    return [packed(word(rom, line + row, index % CELLS_ACROSS)) for row in range(count)]


def text_rows(rom, code):
    if code == NO_BREAK_SPACE:
        # The ROM holds a marker here that the terminal never shows.
        return [0] * TALL_ROWS
    line = code // CELLS_ACROSS * TALL_ROWS
    return [packed(word(rom, line + row, code % CELLS_ACROSS) >> TEXT_FIRST_KEPT_BIT) for row in range(TALL_ROWS)]


def line(code, values):
    return f"{code:02X} " + " ".join(f"{value:02X}" for value in values)


def main():
    with open(sys.argv[1], "rb") as source:
        rom = source.read(ROM_BYTES + 1)
    if len(rom) != ROM_BYTES or hashlib.sha256(rom).hexdigest() != ROM_SHA256:
        raise SystemExit(f"{sys.argv[1]}: not the VT340 character generator ROM 23-236E6")
    print("# The VT340's ReGIS characters, from its character generator ROM 23-236E6.")
    print("# Generated by tools/rom_to_regisfont.py; do not edit.")
    print(f"\n[strike {TALL_ROWS}]")
    for code in ASCII:
        print(line(code, regis_rows(rom, REGIS_FIRST_LINE, code, TALL_ROWS)))
    for code in LATIN_RIGHT_HALF:
        print(line(code, text_rows(rom, code)))
    print(f"\n[strike {SHORT_ROWS}]")
    for code in ASCII:
        print(line(code, regis_rows(rom, REGIS_SHORT_FIRST_LINE, code, SHORT_ROWS)))
    for code in LATIN_RIGHT_HALF:
        rows = text_rows(rom, code)
        print(line(code, [rows[2 * row] | rows[2 * row + 1] for row in range(SHORT_ROWS)]))


if __name__ == "__main__":
    main()
